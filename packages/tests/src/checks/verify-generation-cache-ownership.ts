import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import {
  lstat,
  mkdir,
  readFile,
  readdir,
  realpath,
  unlink,
  writeFile,
} from "node:fs/promises";
import path from "node:path";

interface Options {
  artifactDirectory: string;
  hashes: (name: string) => Promise<Record<string, string>>;
  run: (name: string, args: string[]) => Promise<string>;
  turbo: string;
  webRoot: string;
}

const generatedRoots = [".source", ".next/types", "next-env.d.ts"];

const typegenFiles = new Set([
  "routes.d.ts",
  "validator.ts",
  "root-params.d.ts",
  "cache-life.d.ts",
]);

const digest = (bytes: Uint8Array) =>
  createHash("sha256").update(bytes).digest("hex");

const compare = (left: string, right: string) => left.localeCompare(right);

/** Probe real Turbo restoration without changing authored inputs or hiding build-type bytes. */
export const verifyGenerationCacheOwnership = async ({
  artifactDirectory,
  hashes,
  run,
  turbo,
  webRoot,
}: Options) => {
  const directory = path.join(artifactDirectory, "generation-cache-ownership");

  await mkdir(directory, { recursive: true });

  const [physicalWeb, physicalDirectory] = await Promise.all([
    realpath(webRoot),
    realpath(directory),
  ]);

  const relativeArtifact = path.relative(
    path.dirname(path.dirname(physicalWeb)),
    physicalDirectory
  );

  assert.ok(
    relativeArtifact !== ".." &&
      !relativeArtifact.startsWith(`..${path.sep}`) &&
      !path.isAbsolute(relativeArtifact),
    "Ownership artifacts must stay in the current source workspace"
  );

  const walk = async (relative: string): Promise<string[]> => {
    const target = path.join(physicalWeb, relative);

    const [info, physicalTarget] = await Promise.all([
      lstat(target),
      realpath(target),
    ]);

    const physicalRelative = path.relative(physicalWeb, physicalTarget);

    assert.ok(
      physicalRelative !== ".." &&
        !physicalRelative.startsWith(`..${path.sep}`) &&
        !path.isAbsolute(physicalRelative),
      "Generated paths must remain physically inside this web workspace"
    );

    assert.ok(
      !info.isSymbolicLink(),
      "Generated ownership probe cannot follow links"
    );

    if (info.isFile()) {
      return [relative];
    }

    assert.ok(
      info.isDirectory(),
      "Expected an owned generated file or directory"
    );

    const children = await readdir(target);

    const files = await Promise.all(
      children.map(async (child) => await walk(path.join(relative, child)))
    );

    const sortedFiles = files.flat();
    sortedFiles.sort(compare);

    return sortedFiles;
  };

  const generatedFiles = async () => {
    const files = await Promise.all(generatedRoots.map(walk));

    const sortedFiles = files.flat();
    sortedFiles.sort(compare);

    return sortedFiles;
  };

  const names = await generatedFiles();

  const originals = new Map(
    await Promise.all(
      names.map(
        async (name) =>
          [name, await readFile(path.join(physicalWeb, name))] as const
      )
    )
  );

  const buildOnly = names.filter(
    (name) =>
      name.startsWith(`.next${path.sep}types${path.sep}`) &&
      !typegenFiles.has(path.relative(path.join(".next", "types"), name))
  );

  const guard = buildOnly.find(
    (name) =>
      name.startsWith(path.join(".next", "types", "app") + path.sep) &&
      name.endsWith(".ts")
  );

  assert.ok(
    guard !== undefined,
    "Prepare a production build with a build-only route guard before checking generation cache ownership"
  );

  const guardBytes = originals.get(guard);

  assert.ok(guardBytes !== undefined);
  await Promise.all(
    [...originals].map(async ([name, bytes]) => {
      const backup = path.join(directory, "original", name);

      await mkdir(path.dirname(backup), { recursive: true });
      await writeFile(backup, bytes);
    })
  );

  const restore = async () => {
    const current = await generatedFiles();

    await Promise.all(
      current.flatMap((name) =>
        originals.has(name) ? [] : [unlink(path.join(physicalWeb, name))]
      )
    );
    await Promise.all(
      [...originals].map(async ([name, bytes]) => {
        const target = path.join(physicalWeb, name);

        await mkdir(path.dirname(target), { recursive: true });
        await writeFile(target, bytes);
      })
    );
    assert.deepEqual(
      await generatedFiles(),
      names,
      "Generated file inventory was not restored"
    );
    await Promise.all(
      [...originals].map(async ([name, bytes]) => {
        const actual = await readFile(path.join(physicalWeb, name));

        assert.ok(
          actual.equals(bytes),
          `Generated bytes were not restored: ${name}`
        );
      })
    );
  };

  const command = [turbo, "run", "generate", "--filter=@grasscn/web"];

  const canary = Buffer.concat([
    Buffer.from(`// Grasscn generation ownership canary ${randomUUID()}\n`),
    guardBytes,
  ]);

  const guardFiles = buildOnly.map((name) => {
    const bytes = originals.get(name);

    assert.ok(bytes !== undefined);

    return { path: name, sha256: digest(bytes) };
  });

  const assertBuildOnlyUnchanged = async () => {
    await Promise.all(
      buildOnly.map(async (name) => {
        const expected = originals.get(name);

        assert.ok(expected !== undefined);
        const actual = await readFile(path.join(physicalWeb, name));

        assert.ok(
          actual.equals(expected),
          `Generation cache overwrote build-owned type guard: ${name}`
        );
      })
    );
  };

  const stages: string[] = [];

  const report = {
    buildOnlyFiles: guardFiles,
    canarySha256: digest(canary),
    guard,
    passed: false,
    restored: false,
    stages,
  };

  const failures: unknown[] = [];
  let generationHash = "";

  try {
    const before = await hashes("generation-ownership-before-hashes");

    generationHash = before["@grasscn/web#generate"];
    assert.ok(generationHash !== undefined);
    await writeFile(path.join(physicalWeb, guard), canary);

    const seeded = await hashes("generation-ownership-canary-hashes");

    assert.equal(
      seeded["@grasscn/web#generate"],
      generationHash,
      "Ignored build-only guard must not alter the generation input hash"
    );
    await run("generation-ownership-seed", [...command, "--force"]);
    await writeFile(path.join(physicalWeb, guard), guardBytes);

    const hit = await run("generation-ownership-cache-hit", command);

    assert.match(
      hit,
      /cache hit/u,
      "Ownership regression must execute an actual generation cache hit"
    );
    await assertBuildOnlyUnchanged();
    report.stages.push("actual-cache-hit-preserved-build-owned-types");
    report.passed = true;
  } catch (error) {
    failures.push(error);
  } finally {
    try {
      await restore();
      await run("generation-ownership-canonical-cache", [
        ...command,
        "--force",
      ]);
      report.stages.push("canonical-generation-cache-replaced");

      const canonicalHit = await run(
        "generation-ownership-canonical-cache-hit",
        command
      );

      assert.match(
        canonicalHit,
        /cache hit/u,
        "Canonical cleanup must leave a reusable generation cache"
      );
      await assertBuildOnlyUnchanged();
      report.stages.push("canonical-cache-hit-preserved-build-owned-types");
    } catch (error) {
      failures.push(error);
    } finally {
      try {
        await restore();
        report.restored = true;
      } catch (error) {
        failures.push(error);
      }

      report.passed &&= failures.length === 0;
      await writeFile(
        path.join(directory, "report.json"),
        `${JSON.stringify({ ...report, failures: failures.map(String), generationHash }, null, 2)}\n`
      );
    }
  }

  if (failures.length > 0) {
    throw new AggregateError(
      failures,
      "Generation ownership verification failed; inspect the retained restoration receipt"
    );
  }

  return {
    cacheHit: true as const,
    directory,
    generationHash,
    guardFiles,
    restored: true as const,
  };
};
