test("Dialog keeps long content and its close action reachable in a short viewport",async({page})=>{
  await page.setViewportSize({width:800,height:400})
  await page.goto(`/?${new URLSearchParams({component:"dialog",open:"1",text:Array.from({length:40},()=>"A helpful description.").join("\n")})}`)
  const dialog=page.getByRole("dialog")
  await expect(dialog).toBeVisible()
  const dimensions=await dialog.evaluate(n=>({height:n.clientHeight,scroll:n.scrollHeight,top:n.getBoundingClientRect().top,bottom:n.getBoundingClientRect().bottom}))
  expect(dimensions.scroll).toBeGreaterThan(dimensions.height);expect(dimensions.top).toBeGreaterThanOrEqual(0);expect(dimensions.bottom).toBeLessThanOrEqual(400)
  await dialog.getByRole("button",{name:"Done",exact:true}).click();await expect(dialog).toHaveCount(0)
})
test("Dialog composes custom elements, forwards refs and preserves nested form submission",async({page})=>{
  const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message))
  await page.goto("/?component=dialog-composition")
  const trigger=page.getByRole("button",{name:"Composed trigger",exact:true})
  await trigger.click()
  const dialog=page.getByRole("dialog",{name:"Composed title",exact:true})
  await expect(dialog).toHaveAccessibleDescription("Composed description")
  expect(await dialog.evaluate(n=>n.tagName)).toBe("SECTION")
  await dialog.getByRole("button",{name:"Inspect refs",exact:true}).click()
  await expect(page.getByLabel("Dialog composed refs")).toHaveText("BUTTON,SECTION,ASIDE")
  await dialog.getByRole("textbox",{name:"Dialog form input",exact:true}).fill("World")
  await dialog.getByRole("textbox").press("Enter")
  await expect(page.getByLabel("Dialog submissions")).toHaveText("1");await expect(dialog).toBeVisible()
  await dialog.getByRole("button",{name:"Composed close",exact:true}).click();await expect(dialog).toHaveCount(0);await expect(trigger).toBeFocused()
  expect(errors).toEqual([])
})
test("Dialog buttons play the original click once; hover and Escape remain silent",async({page})=>{
  await page.addInitScript(()=>{(window as any).__dialogSounds=[];HTMLMediaElement.prototype.play=function(){(window as any).__dialogSounds.push({source:this.src,volume:this.volume,rate:this.playbackRate});return Promise.resolve()}})
  const voices=()=>page.evaluate(()=>(window as any).__dialogSounds)
  await page.goto("/?component=dialog")
  const trigger=page.getByRole("button",{name:"Open dialog",exact:true})
  await trigger.hover();expect(await voices()).toEqual([])
  await trigger.click();expect(await voices()).toEqual([{source:minecraftClickSound,volume:.25,rate:1}])
  await page.keyboard.press("Escape");expect(await voices()).toHaveLength(1)
  await trigger.click();await page.getByRole("dialog").getByRole("button",{name:"Done",exact:true}).click();expect(await voices()).toHaveLength(3)
})
