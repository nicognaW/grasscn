import { test, expect } from "./verified-test"
import { minecraftClickSound } from "../../../apps/web/registry/ui/minecraft-sound-assets"

test("Dialog opens, traps keyboard focus, closes with Escape and restores its trigger",async({page})=>{
  await page.goto("/?component=dialog")
  const trigger=page.getByRole("button",{name:"Open dialog",exact:true}),dialog=page.getByRole("dialog")
  await trigger.click();await expect(dialog).toBeVisible()
  await expect(dialog.getByRole("button").first()).toBeFocused()
  await page.keyboard.press("Shift+Tab");await expect(dialog.getByRole("button").last()).toBeFocused()
  await page.keyboard.press("Tab");await expect(dialog.getByRole("button").first()).toBeFocused()
  await page.keyboard.press("Escape");await expect(dialog).toHaveCount(0);await expect(trigger).toBeFocused()
})
