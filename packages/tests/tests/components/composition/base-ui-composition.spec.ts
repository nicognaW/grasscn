import {test, expect} from "@grasscn/tests/test"

test("Base UI state callbacks retain Minecraft defaults and update on the native state", async ({page}) => {
  await page.goto("/?component=base-ui-composition")
  const button = page.getByRole("button", {name: "Stateful button", exact: true})
  await expect(button).toHaveClass(/mc-button/)
  await expect(button).toHaveClass(/state-enabled/)
  await expect(button).toHaveCSS("width", "240px")
  await page.getByRole("button", {name: "Toggle disabled", exact: true}).click()
  await expect(button).toBeDisabled()
  await expect(button).toHaveClass(/state-disabled/)
  await expect(button).toHaveCSS("width", "300px")
  const checkbox = page.getByRole("checkbox", {name: "Stateful checkbox"})
  await expect(checkbox).toHaveClass(/mc-checkbox/)
  await expect(checkbox).toHaveClass(/state-unchecked/)
  await checkbox.click()
  await expect(checkbox).toHaveClass(/state-checked/)
  await expect(checkbox).toHaveCSS("--checked-state", "1")
})

test("Input uses Base UI Field state and popup callbacks receive popup state", async ({page}) => {
  await page.goto("/?component=base-ui-composition")
  const input = page.getByRole("textbox", {name: "Inherited field", exact: true})
  await expect(input).toHaveValue("Hello 世界")
  await expect(input).toBeEnabled()
  await expect(page.getByRole("link", {name: "Composed group text", exact: true})).toHaveAttribute("href", "#group")
  await expect(page.getByRole("link", {name: "Composed sidebar label", exact: true})).toHaveAttribute("href", "#sidebar")
  await page.getByRole("button", {name: "Toggle disabled", exact: true}).click()
  await expect(input).toBeDisabled()
  await page.getByRole("button", {name: "Open stateful dialog", exact: true}).click()
  const dialog = page.getByRole("dialog", {name: "Native state", exact: true})
  await expect(dialog).toHaveClass(/mc-dialog-content/)
  await expect(dialog).toHaveClass(/state-open/)
  await expect(dialog).toHaveCSS("--open-state", "1")
  await page.keyboard.press("Escape")
  await expect(dialog).toHaveCount(0)
})

