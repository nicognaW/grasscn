test("production identity separates Next response cache from compiled pages, chunks and registry delivery", async () => {
  const directory = fs.mkdtempSync(
    path.join(os.tmpdir(), "grasscn-runtime-cache-")
  );

  const source = {
    commit: "cache-boundary",
    treeSha256: "cache-boundary-source",
  };

  const immutable = [
    ".next/server/app/docs/button.html",
    ".next/server/chunks/runtime.js",
    "public/r/button.json",
  ];

  try {
    for (const filename of [".next/BUILD_ID", ...immutable]) {
      fs.mkdirSync(path.dirname(path.join(directory, filename)), {
        recursive: true,
      });
      fs.writeFileSync(path.join(directory, filename), `original ${filename}`);
    }

    const baseline = await productionBuildIdentity({ directory, source });

    const response = path.join(
      directory,
      ".next/server/route-cache/APP_PAGE/source-owner/$/docs/button.rsc"
    );

    fs.mkdirSync(path.dirname(response), { recursive: true });
    fs.writeFileSync(response, "response generated by a runtime request");
    const warmed = await productionBuildIdentity({ directory, source });
    assert.equal(warmed.outputSha256, baseline.outputSha256);
    fs.writeFileSync(response, "updated response cache");
    const rewarmed = await productionBuildIdentity({ directory, source });
    assert.equal(rewarmed.outputSha256, baseline.outputSha256);

    for (const filename of immutable) {
      fs.writeFileSync(
        path.join(directory, filename),
        "changed immutable output"
      );
      // oxlint-disable-next-line no-await-in-loop -- Mutates one shared build tree, checks that exact immutable-output change, then restores it before the next mutation.
      const changed = await productionBuildIdentity({ directory, source });
      assert.notEqual(changed.outputSha256, baseline.outputSha256, filename);
      fs.writeFileSync(path.join(directory, filename), `original ${filename}`);
    }
  } finally {
    assert.ok(path.basename(directory).startsWith("grasscn-runtime-cache-"));
    fs.rmSync(directory, { force: true, recursive: true });
  }
});

test("prepared production requires a completed matching build instead of silently accepting existing output", async () => {
  const root = fs.mkdtempSync(
    path.join(os.tmpdir(), "grasscn-prepared-build-")
  );

  const directory = path.join(root, "web");
  const receiptPath = path.join(root, "completed.json");

  const source = {
    commit: "completed-source",
    status: "",
    treeSha256: "completed-tree",
  };

  try {
    for (const name of [
      "web/.next/server",
      "web/.next/types",
      "web/.source",
      "web/public/r",
      "node_modules/tool",
    ]) {
      fs.mkdirSync(path.join(root, name), { recursive: true });
    }

    fs.writeFileSync(path.join(root, "bun.lock"), '{"workspaces":{}}');
    fs.writeFileSync(
      path.join(root, "node_modules/tool/index.js"),
      "installed tool bytes"
    );
    fs.writeFileSync(
      path.join(directory, ".next/BUILD_ID"),
      "known-completed-build"
    );
    fs.writeFileSync(
      path.join(directory, ".next/server/page.js"),
      "built page"
    );
    fs.writeFileSync(
      path.join(directory, ".next/types/routes.d.ts"),
      "generated route types"
    );
    fs.writeFileSync(
      path.join(directory, ".source/server.ts"),
      "generated MDX source"
    );
    fs.writeFileSync(
      path.join(directory, "next-env.d.ts"),
      "generated Next environment"
    );
    fs.writeFileSync(
      path.join(directory, "public/r/button.json"),
      "delivered registry"
    );
    const options = { directory, receiptPath, root, source };
    await assert.rejects(
      async () => await readPreparedProductionBuild(options),
      /ENOENT/u
    );
    await stampProductionBuild(options);
    await assert.rejects(
      async () => await readPreparedProductionBuild(options),
      /completed build/iu
    );
    await assert.rejects(
      async () =>
        await stampProductionBuild({
          ...options,
          verifiedCommand: [process.execPath, "run", "build"],
          verifiedExitCode: 9,
        }),
      /completed|exit/iu
    );
    await assert.rejects(
      async () =>
        await stampProductionBuild({
          ...options,
          verifiedCommand: [process.execPath, "run", "build", "--dry=json"],
          verifiedExitCode: 0,
        }),
      /root build|command/iu
    );
    await stampProductionBuild({
      ...options,
      verifiedCommand: [process.execPath, "run", "build"],
      verifiedExitCode: 0,
    });
    const prepared = await readPreparedProductionBuild(options);
    assert.equal(prepared.buildId, "known-completed-build");
    assert.deepEqual(prepared.verifiedCommand, [
      process.execPath,
      "run",
      "build",
    ]);
    const bunOptionsBefore = process.env.BUN_OPTIONS;

    try {
      process.env.BUN_OPTIONS = "--smol";
      await assert.rejects(
        async () => await readPreparedProductionBuild(options),
        /environment changed/iu
      );
    } finally {
      if (bunOptionsBefore === undefined) {
        delete process.env.BUN_OPTIONS;
      } else {
        process.env.BUN_OPTIONS = bunOptionsBefore;
      }
    }

    await assert.rejects(
      async () =>
        await readPreparedProductionBuild({
          ...options,
          source: { ...source, treeSha256: "another-tree" },
        }),
      /source/iu
    );

    for (const filename of [
      path.join(root, "node_modules/tool/index.js"),
      path.join(directory, ".source/server.ts"),
      path.join(directory, "next-env.d.ts"),
      path.join(directory, ".next/types/routes.d.ts"),
      path.join(directory, "public/r/button.json"),
      path.join(directory, ".next/server/page.js"),
    ]) {
      const original = fs.readFileSync(filename);
      fs.writeFileSync(filename, "changed bytes");
      // oxlint-disable-next-line no-await-in-loop -- Mutates one shared build tree, checks that exact immutable-output change, then restores it before the next mutation.
      await assert.rejects(
        async () => await readPreparedProductionBuild(options),
        /changed/iu
      );
      fs.writeFileSync(filename, original);
    }

    const originalReceipt = fs.readFileSync(receiptPath, "utf-8");
    const differentEnvironment = parseProductionIdentity(originalReceipt);
    assert.ok(differentEnvironment.preparation);
    differentEnvironment.preparation.environment.bun = "different-runtime";
    fs.writeFileSync(receiptPath, JSON.stringify(differentEnvironment));
    await assert.rejects(
      async () => await readPreparedProductionBuild(options),
      /environment changed/iu
    );
    fs.writeFileSync(receiptPath, originalReceipt);
    const awaitedIdentity1 = await readPreparedProductionBuild(options);
    assert.equal(awaitedIdentity1.buildId, "known-completed-build");
  } finally {
    assert.ok(path.basename(root).startsWith("grasscn-prepared-build-"));
    fs.rmSync(root, { force: true, recursive: true });
  }
});

test("production identity rejects another source and detects changed delivered registry bytes", async () => {
  const directory = fs.mkdtempSync(
    path.join(os.tmpdir(), "grasscn-next-identity-")
  );

  try {
    fs.mkdirSync(path.join(directory, ".next/server"), { recursive: true });
    fs.mkdirSync(path.join(directory, "public/r"), { recursive: true });
    fs.writeFileSync(
      path.join(directory, ".next/BUILD_ID"),
      "known-production"
    );
    fs.writeFileSync(
      path.join(directory, ".next/server/page.js"),
      "original built page"
    );
    fs.writeFileSync(
      path.join(directory, "public/r/button.json"),
      "original delivered registry"
    );
    const source = { commit: "snapshot-one", treeSha256: "source-one" };
    const identity = await productionBuildIdentity({ directory, source });
    assert.equal(identity.buildId, "known-production");
    assert.throws(() => {
      assertProductionSource(identity, {
        ...source,
        treeSha256: "source-two",
      });
    }, /source/iu);
    fs.writeFileSync(
      path.join(directory, "public/r/button.json"),
      "changed delivered registry"
    );

    const changedRegistry = await productionBuildIdentity({
      directory,
      source,
    });

    assert.notEqual(identity.outputSha256, changedRegistry.outputSha256);
    fs.writeFileSync(
      path.join(directory, ".next/server/page.js"),
      "changed built page"
    );

    const awaitedIdentity2 = await productionBuildIdentity({
      directory,
      source,
    });

    assert.notEqual(
      changedRegistry.outputSha256,
      awaitedIdentity2.outputSha256
    );
  } finally {
    assert.ok(path.basename(directory).startsWith("grasscn-next-identity-"));
    fs.rmSync(directory, { force: true, recursive: true });
  }
});

test("source identity binds tracked directory symlink targets without traversing unowned trees", async () => {
  const sandbox = fs.mkdtempSync(
    path.join(os.tmpdir(), "grasscn-source-links-")
  );

  const directory = path.join(sandbox, "repo");
  fs.mkdirSync(directory);

  const git = (args: string[]) =>
    execFileSync("git", args, {
      cwd: directory,
      encoding: "utf-8",
      env: {
        ...process.env,
        GIT_AUTHOR_EMAIL: "source@example.invalid",
        GIT_AUTHOR_NAME: "Source identity fixture",
        GIT_COMMITTER_EMAIL: "source@example.invalid",
        GIT_COMMITTER_NAME: "Source identity fixture",
      },
    });

  const link = path.join(directory, "mirror");
  const fileLink = path.join(directory, "file-link.ts");

  try {
    for (const name of ["tracked-a", "tracked-b"]) {
      fs.mkdirSync(path.join(directory, name));
      fs.writeFileSync(
        path.join(directory, name, "source.ts"),
        "same tracked bytes"
      );
    }

    fs.mkdirSync(path.join(sandbox, "outside"));
    fs.writeFileSync(
      path.join(sandbox, "outside", "source.ts"),
      "outside bytes"
    );
    fs.writeFileSync(
      path.join(directory, ".gitignore"),
      "ignored-*.txt\n**/ignored/\n"
    );
    fs.writeFileSync(
      path.join(directory, "ignored-a.txt"),
      "same linked bytes"
    );
    fs.writeFileSync(
      path.join(directory, "ignored-b.txt"),
      "same linked bytes"
    );
    fs.writeFileSync(path.join(directory, "ordinary.ts"), "ordinary bytes");
    fs.symlinkSync("tracked-a", link, "dir");
    fs.symlinkSync("ignored-a.txt", fileLink, "file");
    git(["init", "--quiet"]);
    git(["config", "core.symlinks", "true"]);
    git(["add", "."]);
    git([
      "-c",
      "commit.gpgsign=false",
      "commit",
      "--quiet",
      "-m",
      "source fixture",
    ]);
    assert.match(git(["ls-files", "--stage", "mirror"]), /^120000 /u);

    const original = await sourceIdentity(directory);
    fs.unlinkSync(link);
    fs.symlinkSync("tracked-b", link, "dir");
    const retargeted = await sourceIdentity(directory);
    assert.notEqual(retargeted.treeSha256, original.treeSha256);
    fs.writeFileSync(
      path.join(directory, "tracked-b/source.ts"),
      "changed tracked bytes"
    );
    const changedTarget = await sourceIdentity(directory);
    assert.notEqual(changedTarget.treeSha256, retargeted.treeSha256);
    fs.writeFileSync(
      path.join(directory, "tracked-b/source.ts"),
      "same tracked bytes"
    );
    const restoredTarget = await sourceIdentity(directory);
    assert.equal(restoredTarget.treeSha256, retargeted.treeSha256);

    fs.unlinkSync(fileLink);
    fs.symlinkSync("ignored-b.txt", fileLink, "file");
    const retargetedFile = await sourceIdentity(directory);
    assert.notEqual(retargetedFile.treeSha256, retargeted.treeSha256);
    fs.writeFileSync(
      path.join(directory, "ignored-b.txt"),
      "changed linked bytes"
    );
    const changedFile = await sourceIdentity(directory);
    assert.notEqual(changedFile.treeSha256, retargetedFile.treeSha256);
    fs.unlinkSync(path.join(directory, "ordinary.ts"));
    const deletedOrdinary = await sourceIdentity(directory);
    assert.notEqual(deletedOrdinary.treeSha256, changedFile.treeSha256);
    fs.writeFileSync(path.join(directory, "ordinary.ts"), "ordinary bytes");
    const restoredOrdinary = await sourceIdentity(directory);
    assert.equal(restoredOrdinary.treeSha256, changedFile.treeSha256);

    fs.writeFileSync(
      path.join(directory, "tracked-b/untracked.ts"),
      "untracked bytes"
    );
    await assert.rejects(
      sourceIdentity(directory),
      /untracked or ignored paths/u
    );
    fs.unlinkSync(path.join(directory, "tracked-b/untracked.ts"));
    fs.mkdirSync(path.join(directory, "tracked-b/ignored"));
    fs.writeFileSync(
      path.join(directory, "tracked-b/ignored/cache.ts"),
      "ignored bytes"
    );
    await assert.rejects(
      sourceIdentity(directory),
      /untracked or ignored paths/u
    );
    fs.unlinkSync(link);
    fs.symlinkSync("../outside", link, "dir");
    await assert.rejects(sourceIdentity(directory), /outside repository/u);
  } finally {
    assert.equal(
      path.dirname(path.resolve(sandbox)),
      path.resolve(os.tmpdir())
    );
    assert.ok(path.basename(sandbox).startsWith("grasscn-source-links-"));
    fs.rmSync(sandbox, { force: true, recursive: true });
  }
});
