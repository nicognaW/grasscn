import { test, expect } from "./verified-test";

test("custom component refs reach their DOM roots and preserve native event cancellation", async ({page}) => {
  await page.goto("/?component=custom-api");
  await page.getByRole("button",{name:"Focus tree by ref"}).click();
  await expect(page.getByRole("group",{name:"Advancement tree"})).toBeFocused();
  await page.getByRole("button",{name:"Focus hotbar by ref"}).click();
  await expect(page.getByRole("button",{name:"Slot 1",exact:true})).toBeFocused();
  await page.getByRole("button",{name:"Slot 2",exact:true}).click();
  await expect(page.locator("#custom-api-event")).toHaveText("slot:1");
  const map=page.getByRole("group",{name:"Map",exact:true});
  await map.click({position:{x:20,y:30}});
  await expect(page.locator("#custom-api-event")).toHaveText("map:10,15");
  await page.getByRole("button",{name:"Toggle cancellation"}).click();
  await page.getByRole("button",{name:"Root",exact:true}).click();
  await expect(page.getByRole("button",{name:"Root",exact:true})).toHaveAttribute("aria-pressed","false");
  await page.getByRole("button",{name:"Slot 3",exact:true}).click();
  await expect(page.getByRole("button",{name:"Slot 2",exact:true})).toHaveAttribute("aria-pressed","true");
  await page.getByRole("button",{name:"Slot 3",exact:true}).hover();await page.mouse.wheel(0,100);
  await expect(page.getByRole("button",{name:"Slot 2",exact:true})).toHaveAttribute("aria-pressed","true");
  await page.getByRole("button",{name:"Next page",exact:true}).click();
  await expect(page.getByRole("document",{name:"Page 1",exact:true})).toBeVisible();
  await map.click({position:{x:40,y:60}});
  await page.getByRole("button",{name:"Sample player",exact:true}).click();
  await page.getByRole("button",{name:"Second offer",exact:true}).click();
  await expect(page.locator("#custom-api-event")).toHaveText("map:10,15");
  await page.getByRole("button",{name:"Toggle cancellation"}).click();
  await page.getByRole("button",{name:"Second offer",exact:true}).click();
  await expect(page.locator("#custom-api-event")).toHaveText("trade:second");
});
